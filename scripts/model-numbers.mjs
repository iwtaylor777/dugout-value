const n1 = (value) => (value === null ? "n/a" : value.toFixed(1));
const pct = (value) => (value === null ? "n/a" : `${(value * 100).toFixed(1)}%`);

function evaluate(settings, list = players) {
  const results = new Map();
  for (const player of list)
    results.set(player.id, valuePlayer(player, settings, database));
  return results;
}

function globalRanks(results) {
  // Rankings drop pending free agents in the offseason view.
  const eligible = players
    .filter((player) => !results.get(player.id).pendingFreeAgent)
    .sort((a, b) => results.get(b.id).total - results.get(a.id).total);
  return new Map(eligible.map((player, index) => [player.id, index + 1]));
}

function averageRanks(values) {
  const order = values
    .map((value, index) => ({ value, index }))
    .sort((a, b) => b.value - a.value);
  const ranks = new Array(values.length);
  let i = 0;
  while (i < order.length) {
    let j = i;
    while (j + 1 < order.length && order[j + 1].value === order[i].value) j += 1;
    const rank = (i + j) / 2 + 1;
    for (let k = i; k <= j; k += 1) ranks[order[k].index] = rank;
    i = j + 1;
  }
  return ranks;
}

function pearson(a, b) {
  const mean = (xs) => xs.reduce((s, x) => s + x, 0) / xs.length;
  const ma = mean(a);
  const mb = mean(b);
  let num = 0;
  let da = 0;
  let db = 0;
  for (let i = 0; i < a.length; i += 1) {
    num += (a[i] - ma) * (b[i] - mb);
    da += (a[i] - ma) ** 2;
    db += (b[i] - mb) ** 2;
  }
  return num / Math.sqrt(da * db);
}

const ranked = players
  .filter((player) => Number(player.futureProjectionUpdate?.rank) > 0)
  .sort((a, b) => a.futureProjectionUpdate.rank - b.futureProjectionUpdate.rank);

function spearman(results) {
  const fg = ranked.map((player) => player.futureProjectionUpdate.rank);
  const model = averageRanks(ranked.map((player) => results.get(player.id).total));
  return { rho: pearson(fg, model), within: model };
}

function spearmanGlobal(ranks) {
  // A pending free agent has no global rank; place it just after the last ranked player.
  const fallback = ranks.size + 1;
  const fg = ranked.map((player) => player.futureProjectionUpdate.rank);
  const model = ranked.map((player) => ranks.get(player.id) ?? fallback);
  return pearson(fg, model);
}

